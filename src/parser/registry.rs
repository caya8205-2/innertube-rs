    #[test]
    fn test_all_574_legacy_classes_are_registered_with_strongly_typed_targets() {
        let count = ParserRegistry::registered_types_count();
        assert_eq!(count, 574, "Expected exactly 574 legacy parser classes from reference-youtubejs");

        let mut direct_count = 0;
        let mut container_count = 0;
        let mut endpoint_count = 0;
        let mut element_count = 0;
        let mut kids_count = 0;

        for class_meta in ParserRegistry::all_classes() {
            assert!(!class_meta.name.is_empty(), "Class name cannot be empty");
            assert!(!class_meta.legacy_path.is_empty(), "Legacy path cannot be empty");
            match class_meta.dispatch_target {
                ParserDispatchTarget::Direct(_) => direct_count += 1,
                ParserDispatchTarget::Container(_) => container_count += 1,
                ParserDispatchTarget::NavigationEndpoint(_) => endpoint_count += 1,
                ParserDispatchTarget::Element(_) => element_count += 1,
                ParserDispatchTarget::Kids(_) => kids_count += 1,
            }
        }

        assert_eq!(direct_count + container_count + endpoint_count + element_count + kids_count, 574);
        assert_eq!(direct_count, 157);
        assert_eq!(container_count, 166);
        assert_eq!(endpoint_count, 70);
        assert_eq!(element_count, 174);
        assert_eq!(kids_count, 7);
    }

